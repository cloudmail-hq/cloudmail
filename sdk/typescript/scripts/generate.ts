/**
 * Regenerate `openapi.json`, `src/generated/schema.ts` and
 * `src/generated/operations.ts` from the Worker's
 * OpenAPI document (`workers/lib/openapi.ts`, served at GET /api/v1/openapi.json).
 *
 *   npm run generate          write both files
 *   npm run check:generated   exit 1 when either is stale (CI)
 *
 * The document is imported from source rather than fetched, so generation is
 * offline and always matches the commit being built.
 */

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { openApiDocument } from "../../../workers/lib/openapi";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const specPath = resolve(root, "openapi.json");
const schemaPath = resolve(root, "src/generated/schema.ts");
const operationsPath = resolve(root, "src/generated/operations.ts");

const HEADER = `/**
 * Generated by sdk/typescript/scripts/generate.ts from workers/lib/openapi.ts.
 * Do not edit by hand: run \`npm run generate\` in sdk/typescript.
 */

/* eslint-disable */
`;

const METHODS = ["get", "post", "put", "patch", "delete"] as const;

/** operationId -> method and path, so the client never spells a path by hand. */
function renderOperations(doc: { paths: Record<string, Record<string, { operationId?: string }>> }): string {
	const lines: string[] = [];
	for (const [path, item] of Object.entries(doc.paths)) {
		for (const method of METHODS) {
			const id = item[method]?.operationId;
			if (id) lines.push(`\t${id}: { method: "${method.toUpperCase()}", path: ${JSON.stringify(path)} },`);
		}
	}
	return `${HEADER}\nexport const OPERATIONS = {\n${lines.join("\n")}\n} as const;\n\nexport type OperationId = keyof typeof OPERATIONS;\n`;
}

async function render(): Promise<{ spec: string; schema: string; operations: string }> {
	const spec = `${JSON.stringify(openApiDocument, null, "\t")}\n`;
	// A JSON round trip drops `undefined`s and gives the generator plain data.
	const ast = await openapiTS(JSON.parse(spec), { alphabetize: false, exportType: false });
	const schema = `${HEADER}\n${astToString(ast)}`;
	return { spec, schema, operations: renderOperations(JSON.parse(spec)) };
}

async function current(path: string): Promise<string | null> {
	try {
		return await readFile(path, "utf8");
	} catch {
		return null;
	}
}

const { spec, schema, operations } = await render();

if (process.argv.includes("--check")) {
	const stale: string[] = [];
	if ((await current(specPath)) !== spec) stale.push("sdk/typescript/openapi.json");
	if ((await current(schemaPath)) !== schema) stale.push("sdk/typescript/src/generated/schema.ts");
	if ((await current(operationsPath)) !== operations) stale.push("sdk/typescript/src/generated/operations.ts");
	if (stale.length) {
		console.error(`Stale generated files: ${stale.join(", ")}.\nRun \`npm run generate\` in sdk/typescript and commit the result.`);
		process.exit(1);
	}
	console.log("Generated SDK types are up to date.");
} else {
	await mkdir(dirname(schemaPath), { recursive: true });
	await writeFile(specPath, spec);
	await writeFile(schemaPath, schema);
	await writeFile(operationsPath, operations);
	console.log(`Wrote ${specPath}, ${schemaPath} and ${operationsPath}.`);
}
