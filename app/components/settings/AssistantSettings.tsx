/**
 * Settings → AI assistant.
 *
 * Two groups. "For you" is per user (`/api/v1/me/assistant`): one-liners in the
 * list, and the daily brief's time, zone and email. "For this instance" is the
 * admin-owned spend control (`/api/v1/ai/settings`), shown read-only to others.
 */

import { useEffect, useMemo, useState } from "react";
import { Loader2, Sparkles } from "lucide-react";
import { Switch } from "~/components/ui/switch";
import { showToast } from "~/lib/toast";
import {
	useAiSettings,
	useAssistantPrefs,
	useGenerateBrief,
	useUpdateAiSettings,
	useUpdateAssistantPrefs,
	useBrief,
} from "~/queries/assistant";
import { MAX_DAILY_CAP, MAX_EMBED_DAILY_CAP } from "shared/ai-settings";
import { useQuery } from "@tanstack/react-query";
import api from "~/services/api";

function Row({
	title,
	description,
	children,
	htmlFor,
	wide,
}: {
	title: string;
	description: string;
	children: React.ReactNode;
	htmlFor?: string;
	/** The control is wider than a switch: stack it under the text on mobile. */
	wide?: boolean;
}) {
	return (
		<div className={wide ? "flex flex-col gap-3 p-5 sm:flex-row sm:items-start sm:justify-between sm:gap-4" : "flex items-start justify-between gap-4 p-5"}>
			<div className="min-w-0">
				<h3 className="text-sm font-medium text-text-primary">
					{htmlFor ? <label htmlFor={htmlFor}>{title}</label> : title}
				</h3>
				<p className="mt-1 text-sm text-text-secondary">{description}</p>
			</div>
			<div className="shrink-0">{children}</div>
		</div>
	);
}

/** Every zone the runtime knows, falling back to a short list on old browsers. */
function timeZones(): string[] {
	const intl = Intl as unknown as { supportedValuesOf?: (key: string) => string[] };
	try {
		const list = intl.supportedValuesOf?.("timeZone");
		if (list && list.length > 0) return list.includes("UTC") ? list : ["UTC", ...list];
	} catch {
		// fall through
	}
	return ["UTC", "Europe/London", "Europe/Berlin", "America/New_York", "America/Los_Angeles", "Asia/Kolkata", "Asia/Tokyo", "Australia/Sydney"];
}

const fieldClass =
	"h-9 rounded-[6px] border border-border bg-card px-2 text-sm text-text-primary focus:outline-none focus-visible:ring-2 focus-visible:ring-ring/40 disabled:opacity-50 touch:h-11";

export default function AssistantSettings({ isAdmin }: { isAdmin: boolean }) {
	const { data: prefs, isLoading } = useAssistantPrefs();
	const update = useUpdateAssistantPrefs();
	const { data: ai } = useAiSettings();
	const updateAi = useUpdateAiSettings();
	const { data: briefState } = useBrief(!!prefs?.brief.enabled);
	const generate = useGenerateBrief();
	const zones = useMemo(timeZones, []);
	const [cap, setCap] = useState<string>("");
	const [embedCap, setEmbedCap] = useState<string>("");
	const { data: semantic } = useQuery({
		queryKey: ["ai", "semantic"],
		queryFn: ({ signal }) => api.getSemanticAvailability({ signal }),
		staleTime: 60_000,
	});

	useEffect(() => {
		if (ai) {
			setCap(String(ai.dailyCapPerMailbox));
			setEmbedCap(String(ai.embedDailyCapPerMailbox));
		}
	}, [ai]);

	const noIdentity = !isLoading && prefs === null;
	const save = (patch: Parameters<typeof update.mutate>[0]) =>
		update.mutate(patch, {
			onError: () => showToast({ kind: "error", message: "Could not save that setting." }),
		});
	const saveAi = (patch: Parameters<typeof updateAi.mutate>[0]) =>
		updateAi.mutate(patch, {
			onError: () => showToast({ kind: "error", message: "Could not save that setting." }),
		});

	// Suggest the browser's zone the first time the brief is turned on.
	const browserZone = typeof Intl !== "undefined" ? Intl.DateTimeFormat().resolvedOptions().timeZone : "UTC";
	const brief = prefs?.brief;

	return (
		<section className="space-y-6">
			<div className="space-y-3">
				<div className="flex items-center gap-2">
					<Sparkles size={14} className="text-text-tertiary" />
					<h2 className="text-base font-semibold text-text-primary">AI assistant</h2>
					{(update.isPending || updateAi.isPending) && (
						<Loader2 size={12} className="animate-spin text-text-tertiary" aria-label="Saving" />
					)}
				</div>
				<p className="text-sm text-text-secondary">
					Short AI summaries of conversations and a daily brief. Summaries are generated by Workers AI on this deployment, are
					never made for Spam or Trash, and can be wrong.
				</p>
				{noIdentity && (
					<p className="rounded-[6px] bg-amber-500/10 px-3 py-2 text-sm text-text-secondary">
						Personal settings need a signed-in account. Sign in to change them.
					</p>
				)}

				<div className="divide-y divide-border/60 rounded-[8px] bg-card ring-1 ring-border">
					<Row
						title="Summaries in the message list"
						description="Show an AI one-line summary under each conversation instead of the first line of the message."
					>
						<Switch
							checked={prefs?.listSummaries ?? true}
							onCheckedChange={(listSummaries) => save({ listSummaries })}
							disabled={isLoading || noIdentity}
							aria-label="Summaries in the message list"
						/>
					</Row>

					<Row
						title="Daily brief"
						description="Each morning, a Today card at the top of your inbox: what came in, what needs your reply, and sent mail still waiting on others."
					>
						<Switch
							checked={brief?.enabled ?? false}
							onCheckedChange={(enabled) =>
								save(
									enabled && brief?.timeZone === "UTC" && browserZone !== "UTC"
										? { brief: { enabled, timeZone: browserZone } }
										: { brief: { enabled } },
								)
							}
							disabled={isLoading || noIdentity}
							aria-label="Daily brief"
						/>
					</Row>

					{brief?.enabled && (
						<>
							<Row title="Brief time" description="Local time the brief is prepared." htmlFor="brief-time" wide>
								<div className="flex flex-wrap items-center gap-2">
									<input
										id="brief-time"
										type="time"
										step={60}
										value={brief.time}
										onChange={(e) => e.target.value && save({ brief: { time: e.target.value.slice(0, 5) } })}
										className={fieldClass}
									/>
									<select
										aria-label="Time zone"
										value={brief.timeZone}
										onChange={(e) => save({ brief: { timeZone: e.target.value } })}
										className={`${fieldClass} max-w-[14rem]`}
									>
										{(zones.includes(brief.timeZone) ? zones : [brief.timeZone, ...zones]).map((z) => (
											<option key={z} value={z}>
												{z}
											</option>
										))}
									</select>
								</div>
							</Row>
							<Row
								title="Email me the brief"
								description="Also send it to your sign-in address from this deployment's system sender."
							>
								<Switch
									checked={brief.email}
									onCheckedChange={(email) => save({ brief: { email } })}
									aria-label="Email me the brief"
								/>
							</Row>
							<div className="flex flex-wrap items-center gap-3 p-5">
								<button
									type="button"
									onClick={() =>
										generate.mutate(undefined, {
											onSuccess: () => showToast({ message: "Brief updated. It is at the top of your inbox." }),
											onError: () => showToast({ kind: "error", message: "Could not build the brief." }),
										})
									}
									disabled={generate.isPending}
									className="inline-flex min-h-9 items-center gap-2 rounded-[6px] bg-accent px-3 text-sm font-semibold text-accent-foreground disabled:opacity-60 touch:min-h-11"
								>
									{generate.isPending && <Loader2 size={13} className="animate-spin" aria-hidden />}
									Build today's brief now
								</button>
								{briefState?.nextRunAt && (
									<span className="text-xs text-text-tertiary">
										{/* In the brief's zone, which may not be this browser's. */}
										Next brief{" "}
										{new Date(briefState.nextRunAt).toLocaleString(undefined, {
											weekday: "short",
											hour: "2-digit",
											minute: "2-digit",
											timeZone: brief.timeZone,
										})}{" "}
										({brief.timeZone})
									</span>
								)}
							</div>
						</>
					)}
				</div>
			</div>

			<div className="space-y-3">
				<h3 className="text-sm font-semibold text-text-primary">For this deployment{isAdmin ? "" : " (set by an administrator)"}</h3>
				<div className="divide-y divide-border/60 rounded-[8px] bg-card ring-1 ring-border">
					<Row title="Generate summaries" description="Turn off to stop all new summary model calls. Existing summaries stay.">
						<Switch
							checked={ai?.summaries ?? true}
							onCheckedChange={(summaries) => saveAi({ summaries })}
							disabled={!isAdmin || !ai}
							aria-label="Generate summaries"
						/>
					</Row>
					<Row
						title="Summarise newsletters and notifications"
						description="Mail with List-Id, List-Unsubscribe, Precedence: bulk or a noreply sender. Turn this off to skip its one-liner and bullets and save the daily limit for people."
					>
						<Switch
							checked={ai?.bulkSummaries ?? true}
							onCheckedChange={(bulkSummaries) => saveAi({ bulkSummaries })}
							disabled={!isAdmin || !ai}
							aria-label="Summarise newsletters and notifications"
						/>
					</Row>
					<Row
						title="Daily limit per mailbox"
						description="Most summaries generated per mailbox per day (UTC), including the Summarize button. Each is one model call for the one-liner and bullets. The remainder waits for the next day."
						htmlFor="ai-cap"
					>
						<input
							id="ai-cap"
							type="number"
							inputMode="numeric"
							min={0}
							max={MAX_DAILY_CAP}
							value={cap}
							disabled={!isAdmin || !ai}
							onChange={(e) => setCap(e.target.value)}
							onBlur={() => {
								const n = Number(cap);
								if (Number.isInteger(n) && n >= 0 && n <= MAX_DAILY_CAP && n !== ai?.dailyCapPerMailbox) {
									saveAi({ dailyCapPerMailbox: n });
								} else if (ai) setCap(String(ai.dailyCapPerMailbox));
							}}
							className={`${fieldClass} w-24 tabular-nums`}
						/>
					</Row>
					<Row
						title="Semantic search and Ask"
						description={
							semantic && !semantic.bound
								? "Not set up: this deployment has no Vectorize index bound, so search is keyword-only. See the README to create it."
								: "Embed new mail (never Spam or Trash) so search understands meaning and you can ask questions of your inbox. Off falls back to keyword search."
						}
					>
						<Switch
							checked={ai?.semantic ?? true}
							onCheckedChange={(on) => saveAi({ semantic: on })}
							disabled={!isAdmin || !ai}
							aria-label="Semantic search and Ask"
						/>
					</Row>
					<Row
						title="Daily embedding limit per mailbox"
						description="Most text passages embedded per mailbox per day (UTC). A message is one to six passages. The remainder waits for the next day."
						htmlFor="ai-embed-cap"
					>
						<input
							id="ai-embed-cap"
							type="number"
							inputMode="numeric"
							min={0}
							max={MAX_EMBED_DAILY_CAP}
							value={embedCap}
							disabled={!isAdmin || !ai || ai.semantic === false}
							onChange={(e) => setEmbedCap(e.target.value)}
							onBlur={() => {
								const n = Number(embedCap);
								if (Number.isInteger(n) && n >= 0 && n <= MAX_EMBED_DAILY_CAP && n !== ai?.embedDailyCapPerMailbox) {
									saveAi({ embedDailyCapPerMailbox: n });
								} else if (ai) setEmbedCap(String(ai.embedDailyCapPerMailbox));
							}}
							className={`${fieldClass} w-24 tabular-nums`}
						/>
					</Row>
				</div>
			</div>
		</section>
	);
}
