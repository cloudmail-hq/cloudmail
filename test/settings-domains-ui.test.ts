import { describe, expect, it } from "vitest";
import { describeSecondFactor } from "~/lib/auth-helpers";
import { contrastRatio, INDIGO_ACCENT, MIN_UI_CONTRAST, parseHex } from "../shared/color-contrast";
import { dnsStatusRows, dnsStatusSummary } from "../shared/domains-ui";
import { flattenPages, nextPageNumber } from "../shared/paged-list";
import {
	resolveSection,
	sectionForLegacyHash,
	visibleSections,
} from "../shared/settings-sections";
import { evaluateAudit, expectedRecords, answerKey, CF_MX_HOSTS } from "../workers/lib/dns-audit";
import { DEFAULT_ACCENT_COLOR, getBranding } from "../workers/lib/branding";

describe("settings sections", () => {
	const admin = { isAdmin: true, passwordMode: true, managesSomeMailbox: true };
	const member = { isAdmin: false, passwordMode: true, managesSomeMailbox: false };

	it("shows admins every section, account first", () => {
		const ids = visibleSections(admin).map((s) => s.id);
		expect(ids[0]).toBe("account");
		expect(ids).toEqual(
			expect.arrayContaining(["domains", "cloudflare", "users", "access", "branding", "suppressions", "webhooks", "ai-providers"]),
		);
	});

	it("hides admin pages from members, and webhooks unless they manage a mailbox", () => {
		const ids = visibleSections(member).map((s) => s.id);
		// The AI assistant page is per user, so every member gets it.
		expect(ids).toEqual(["account", "preferences", "notifications", "auto-draft", "assistant"]);
		expect(visibleSections({ ...member, managesSomeMailbox: true }).map((s) => s.id)).toContain("webhooks");
	});

	it("drops account and users in Access mode", () => {
		const ids = visibleSections({ ...admin, passwordMode: false }).map((s) => s.id);
		expect(ids).not.toContain("account");
		expect(ids).not.toContain("users");
	});

	it("gives every page exactly one save model", () => {
		for (const s of visibleSections(admin)) expect(["autosave", "form"]).toContain(s.save);
	});

	it("maps old single-page anchors onto the routed pages", () => {
		expect(sectionForLegacyHash("#domains")).toBe("domains");
		expect(sectionForLegacyHash("#display")).toBe("preferences");
		expect(sectionForLegacyHash("#appearance")).toBe("preferences");
		expect(sectionForLegacyHash("#notifications")).toBe("sending");
		expect(sectionForLegacyHash("#nope")).toBeNull();
		expect(sectionForLegacyHash("")).toBeNull();
	});

	it("falls back to the first visible page for unknown or hidden sections", () => {
		const visible = visibleSections(member);
		expect(resolveSection("domains", visible)?.id).toBe("account");
		expect(resolveSection(undefined, visible)?.id).toBe("account");
		expect(resolveSection("auto-draft", visible)?.id).toBe("auto-draft");
	});
});

describe("DNS status rows", () => {
	const host = "example.dev";
	const records = expectedRecords(host);

	it("lists MX, SPF, DKIM, return-path, bounce MX and DMARC, unchecked without an audit", () => {
		const rows = dnsStatusRows(records, null);
		expect(rows.map((r) => r.id)).toEqual(["mx", "spf", "dkim", "bounce_mx", "bounce_spf", "sending_dkim", "dmarc"]);
		expect(rows.every((r) => r.status === "unchecked")).toBe(true);
		const mx = rows.find((r) => r.id === "mx")!;
		expect(mx.expected).toEqual(CF_MX_HOSTS.map((h, i) => `${[13, 24, 86][i]} ${h}`));
		expect(mx.name).toBe(host);
	});

	it("keeps SPF and DKIM apart although both are routing TXT records", () => {
		const rows = dnsStatusRows(records, null);
		const spf = rows.find((r) => r.id === "spf")!;
		const dkim = rows.find((r) => r.id === "dkim")!;
		expect(spf.expected).toEqual(["v=spf1 include:_spf.mx.cloudflare.net ~all"]);
		expect(spf.generated).toBe(false);
		expect(dkim.name).toBe(`cf2024-1._domainkey.${host}`);
		// The key is generated by Cloudflare, so there is nothing to copy.
		expect(dkim.generated).toBe(true);
	});

	it("carries pass/warn/fail, found values and messages from the audit", () => {
		const answers = {
			[answerKey(host, "MX")]: CF_MX_HOSTS.map((h, i) => `${i + 1} ${h}`),
			[answerKey(host, "TXT")]: ["v=spf1 include:_spf.google.com ~all"],
			[answerKey(`_dmarc.${host}`, "TXT")]: [],
		};
		const audit = evaluateAudit(host, answers, { now: 1 });
		const rows = dnsStatusRows(records, audit);
		const by = Object.fromEntries(rows.map((r) => [r.id, r]));
		expect(by.mx.status).toBe("pass");
		expect(by.spf.status).toBe("warn");
		expect(by.spf.found).toEqual(["v=spf1 include:_spf.google.com ~all"]);
		expect(by.spf.message).toMatch(/missing/);
		// Unanswered lookups count as "could not check" (warn), never fail.
		expect(by.dkim.status).toBe("warn");
		expect(by.dmarc.status).toBe("warn");
		expect(dnsStatusSummary(rows)).toEqual({ pass: 1, warn: 6, fail: 0, unchecked: 0 });
	});

	it("uses API-reported sending records when present", () => {
		const custom = expectedRecords(host, {
			sendingDns: [
				{ purpose: "sending", type: "TXT", name: `sel1._domainkey.${host}`, value: "v=DKIM1; p=abc" },
			],
		});
		const row = dnsStatusRows(custom, null).find((r) => r.id === "sending_dkim")!;
		expect(row.expected).toEqual(["v=DKIM1; p=abc"]);
		expect(row.generated).toBe(false);
	});
});

describe("two-factor status", () => {
	it("does not say Off while passkeys exist", () => {
		const s = describeSecondFactor({ totpEnabled: false, passkeyCount: 3 });
		expect(s.label).not.toBe("Off");
		expect(s.label).toBe("Passkeys only");
		expect(s.detail).toMatch(/3 passkeys/);
		// And it doesn't claim password sign-ins are protected.
		expect(s.detail).toMatch(/no second step/);
	});

	it("reads On with an authenticator app, and Off with nothing", () => {
		expect(describeSecondFactor({ totpEnabled: true, passkeyCount: 0 }).label).toBe("On: authenticator app");
		expect(describeSecondFactor({ totpEnabled: true, passkeyCount: 1 }).detail).toMatch(/1 passkey\b/);
		expect(describeSecondFactor({ totpEnabled: false, passkeyCount: 0 }).label).toBe("Off");
	});
});

describe("branding accent", () => {
	it("defaults to the indigo accent, which clears 3:1 on white", () => {
		expect(DEFAULT_ACCENT_COLOR).toBe(INDIGO_ACCENT);
		expect(contrastRatio(INDIGO_ACCENT, "#fff")!).toBeGreaterThanOrEqual(MIN_UI_CONTRAST);
	});

	it("flags the old lime default as below 3:1", () => {
		expect(contrastRatio("#BFFF00", "#FFFFFF")!).toBeLessThan(MIN_UI_CONTRAST);
	});

	it("parses 3- and 6-digit hex and rejects junk", () => {
		expect(parseHex("#fff")).toEqual([255, 255, 255]);
		expect(parseHex("4F46E5")).toEqual([79, 70, 229]);
		expect(parseHex("indigo")).toBeNull();
		expect(contrastRatio("#000", "#fff")).toBeCloseTo(21, 0);
		expect(contrastRatio("nope", "#fff")).toBeNull();
	});

	it("moves a record saved with the old lime default onto indigo, but keeps chosen colours", async () => {
		const bucket = (value: unknown) =>
			({ get: async () => ({ json: async () => value }) }) as unknown as R2Bucket;
		expect((await getBranding(bucket({ appName: "X", accentColor: "#bfff00" }))).accentColor).toBe(INDIGO_ACCENT);
		expect((await getBranding(bucket({ appName: "X", accentColor: "#ff0055" }))).accentColor).toBe("#ff0055");
	});
});

describe("load-more pages", () => {
	it("flattens pages and drops ids repeated across a page boundary", () => {
		const pages = [
			[{ id: "a" }, { id: "b" }],
			[{ id: "b" }, { id: "c" }],
		];
		expect(flattenPages(pages, (x) => x.id).map((x) => x.id)).toEqual(["a", "b", "c"]);
	});

	it("asks for the next page only while rows remain", () => {
		expect(nextPageNumber(1, 40, 100)).toBe(2);
		expect(nextPageNumber(3, 40, 100)).toBeUndefined();
		expect(nextPageNumber(1, 40, 40)).toBeUndefined();
		expect(nextPageNumber(0, 40, 0)).toBeUndefined();
		expect(nextPageNumber(1, 0, 10)).toBeUndefined();
	});
});
